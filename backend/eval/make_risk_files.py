"""Write test claims whose expected risk score is exactly 100, 70, 50 and 30.

Each claim is a generated scenario (fictional patient, hospital, bills and policy) with planted problems chosen so
the findings' points add up to the target. Only problems that code catches on its own are used (no Gemini
judgement, no earlier claim needed), so the live result should match.

python -m eval.make_risk_files ../filesToTest
"""

import itertools
import json
import shutil
import sys
import time
from pathlib import Path

from claimlens.pipeline.report import WEIGHTS, risk_band
from eval.scenarios.forgeries import FORGERIES
from eval.scenarios.recipe import make_recipe
from eval.scenarios.render import render
from eval.scenarios.truth import truth_of

TARGETS = (100, 70, 50, 30)
FMT = "one_pdf"  # digital PDFs: the file-history and font checks work on them
# deterministic, code-only problems; reused_invoice needs an earlier claim, the rest rely on Gemini's judgement
CANDIDATES = ["retype_total", "editor_resave", "late_edit", "incremental_save", "pharmacy_after_discharge",
              "admit_after_discharge", "claimed_mismatch", "duplicate_page", "missing_page", "extra_room_days",
              "duplicate_line", "wrong_policy_number", "waiting_period", "room_over_limit"]


def _score(truth) -> int:
    return min(100, sum(WEIGHTS[s] for sevs in truth.severities.values() for s in sevs))


def _compatible(names) -> bool:
    return all(not (FORGERIES[n].conflicts & set(names)) for n in names)


def find(target: int, run: str, used: set[int], seeds=range(1, 400)):
    """The fewest planted problems (then the lowest unused seed) that give exactly `target`.

    Each claim gets its own seed and the run tag is unique, so no two claims (and no earlier upload) share an
    invoice number: otherwise the duplicate-invoice check rightly flags the later one."""
    for size in range(0, 5):
        for names in itertools.combinations(CANDIDATES, size):
            if not _compatible(names):
                continue
            for seed in seeds:
                if seed in used:
                    continue
                recipe = make_recipe(seed, run, rules=False)
                if not all(FORGERIES[n].needs(recipe) for n in names):
                    continue
                for n in names:
                    recipe = FORGERIES[n].apply(recipe)
                truth = truth_of(recipe, list(names), FMT, ocr=True)
                if truth.status == "READY" and _score(truth) == target:
                    return seed, list(names), recipe, truth
    raise SystemExit(f"no combination found for {target}")


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    run, used, summary = f"risk{int(time.time())}", set(), []
    for target in TARGETS:
        seed, names, recipe, truth = find(target, run, used)
        used.add(seed)
        folder = out / f"score-{target}"
        shutil.rmtree(folder, ignore_errors=True)  # never leave files from an earlier generation
        for card, name, data in render(recipe, names, FMT):
            (folder / card).mkdir(parents=True, exist_ok=True)
            (folder / card / name).write_bytes(data)
        findings = {code: sevs for code, sevs in sorted(truth.severities.items())}
        expected = {"score": target, "band": risk_band(target), "seed": seed, "planted": names,
                    "findings": findings, "payable": truth.payable, "recommendation": truth.recommendation}
        (folder / "expected.json").write_text(json.dumps(expected, indent=2))
        summary.append(expected | {"folder": folder.name})
        print(f"{target}: seed {seed}, planted {names} -> {findings}")
    lines = ["# Test claims by expected risk score", "",
             "Generated by `python -m eval.make_risk_files` (fictional people, hospitals and policies).",
             "Upload `claim/` files to the Claim form and `policy/` files to the Policy form.", "",
             "**Each set is single use.** ClaimLens remembers every invoice number it has seen (across all accounts), "
             "so uploading the same files a second time adds critical *duplicate invoice* findings and the score jumps "
             "to 100. To test again, regenerate a fresh set first.", "",
             "| Folder | Score | Band | Planted problems | Expected findings (severity) |",
             "| --- | --- | --- | --- | --- |"]
    for s in summary:
        found = ", ".join(f"{c} ({'/'.join(v)})" for c, v in s["findings"].items())
        lines.append(f"| {s['folder']} | {s['score']} | {s['band']} | {', '.join(s['planted']) or 'none'} | {found} |")
    lines += ["", "Points: critical 40, high 20, medium 10, low 5, coverage 0; capped at 100. "
              "Bands: under 30 low, 30–59 review, 60+ high."]
    (out / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "../filesToTest"))
