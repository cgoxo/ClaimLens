"""Upload each filesToTest/score-N claim to a running ClaimLens and compare with its expected.json.

python -m eval.run_risk_files ../filesToTest --base-url https://… --token <Firebase ID token>
python -m eval.run_risk_files ../filesToTest --base-url http://localhost:8080 --dev-user me@x.com
"""

import argparse
import json
import time
from collections import Counter
from datetime import date
from pathlib import Path

import httpx

CARDS = [{"id": "claim", "role": "claim"}, {"id": "policy", "role": "policy"}]
DONE = {"READY", "FAILED", "REJECTED"}


def run_one(http: httpx.Client, folder: Path, timeout: int) -> dict:
    expected = json.loads((folder / "expected.json").read_text())
    r = http.post("/api/cases", json={"cards": CARDS})
    r.raise_for_status()
    case_id = r.json()["case_id"]
    for card in ("claim", "policy"):
        for f in sorted((folder / card).iterdir()):
            http.post(f"/api/cases/{case_id}/files", data={"card_id": card},
                      files={"file": (f.name, f.read_bytes(), "application/pdf")}).raise_for_status()
    http.post(f"/api/cases/{case_id}/submit").raise_for_status()
    started, case = time.time(), {}
    while time.time() - started < timeout:
        r = http.get(f"/api/cases/{case_id}")
        if r.status_code == 200:
            case = r.json()
            if case["status"] in DONE:
                break
        time.sleep(5)
    found = Counter(f["code"] for f in case.get("findings", []))
    want = Counter({c: len(v) for c, v in expected["findings"].items()})
    rec = ((case.get("current") or case.get("analysis") or {}).get("recommendation") or {}).get("action")
    return {"folder": folder.name, "case_id": case_id, "status": case.get("status"), "seconds": round(time.time() - started),
            "expected_score": expected["score"], "score": case.get("score"),
            "expected_band": expected["band"], "band": case.get("risk"),
            "missing": dict(want - found), "extra": dict(found - want),
            "payable": case.get("payable"), "recommendation": rec,
            "pass": case.get("status") == "READY" and case.get("score") == expected["score"]}


def report(rows: list[dict], base_url: str) -> str:
    ok = sum(r["pass"] for r in rows)
    lines = [f"# Risk-score test claims: live ({date.today().isoformat()})", "",
             f"Target: {base_url}. Files: `filesToTest/` (generated by `eval.make_risk_files`).", "",
             f"## {ok}/{len(rows)} landed on the expected score", "",
             "| Folder | Expected | Got | Band (exp → got) | Status | Missing findings | Extra findings | Recommendation | Case | Seconds |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['folder']} | {r['expected_score']} | {r['score']} | {r['expected_band']} → {r['band']} | "
                     f"{r['status']} | {r['missing'] or '–'} | {r['extra'] or '–'} | {r['recommendation']} | "
                     f"{r['case_id']} | {r['seconds']} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("folder", type=Path)
    ap.add_argument("--base-url", required=True)
    who = ap.add_mutually_exclusive_group(required=True)
    who.add_argument("--token")
    who.add_argument("--token-file", type=Path)
    who.add_argument("--dev-user")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    token = args.token or (args.token_file.read_text().strip() if args.token_file else None)
    headers = {"Authorization": f"Bearer {token}"} if token else {"X-Dev-User": args.dev_user}
    rows = []
    with httpx.Client(base_url=args.base_url, headers=headers, timeout=120) as http:
        for folder in sorted(p for p in args.folder.iterdir() if (p / "expected.json").is_file()):
            row = run_one(http, folder, args.timeout)
            rows.append(row)
            print(json.dumps(row), flush=True)
    text = report(rows, args.base_url)
    if args.out:
        args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
